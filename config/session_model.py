# session_model.py —— 台指期盤段模型:邊界常數 + 五狀態分類
"""盤段模型的**單一真相**。wiki `Session-Model` §1(七個值)、§3(對照表)、§4(歸檔樞紐)。

## 🔒 這個檔案是 vendored 的:四份必須**逐位元相同**

```
TXF-Trading-Workspace/session_model.py              ← 正典(本檔)
  ├── txf-quant-platform/config/session_model.py
  ├── txf-data-lake/config/session_model.py
  └── txf-gale-engine/config/session_model.py
```

`txf-quant-platform/tools/check_time_constants.py` 每天比對四份的 SHA256
(掛在 `daily_sync.py` 的第一步 `time_const`)—— 不同就吵。

**為什麼是逐位元複製,而不是 pip 套件**:四個 repo 的生命週期不同(platform 走 promote
紀律、data-lake 隨時可改、gale 半退役、streaming 生產在 Ubuntu)。共用**程式碼**會把最嚴的
紀律傳染給最鬆的那個。而 pip 套件的成本更不划算:四個 .venv、版本可能歪、動 .venv 要停
run_trade、還有「別跑裸 `uv sync`」的地雷 —— **為了七個常數 + 一個函式,那個機器太重**。
逐位元複製 + 雜湊比對買到的是:漂移**不可能**(相同 ⇒ 行為必然相同)、零耦合、而且**偵測得到**。

🔒 **本檔只准放「近乎凍結」的東西**:邊界值 + 五狀態分類 + 歸檔標籤推導。
   **分桶 / snap / 重採樣一律不准進來** —— 那些常改,混進來會讓四份副本天天要同步,
   而「改動要有儀式感」這個門檻就失效了。各 repo 怎麼**接線**是各 repo 自己的事。

🔒 **相依只准 `datetime` 與 `enum`**(純 stdlib)。多一個相依,這個檔就複製不進
   只有 polars 的 data-lake 或只有 dash 的 gale。檢查器會擋。

## ⚠️⚠️ 這些值是**資料的 schema 歷史**,不是 config

六年 parquet 的 `session` 與 `date` 欄,是用**當時的邊界值**寫進去的。
改值 = 讓新舊資料在同一個欄位裡有兩種語意,**而且不會報錯**。
> **要改,得連同重建全史湖一起做。**
"""
from datetime import date, datetime, time, timedelta
from enum import StrEnum

# ══════════════════════════════════════════════════════════════════════════
#  §1 七個值 —— 五狀態模型的邊界
#
#      [08:30, 08:45)          日盤試撮
#      [08:45, 13:45 + 餘裕)   日盤
#      [13:45:05, 14:50)       休市
#      [14:50, 15:00)          夜盤試撮
#      [15:00, 05:00 + 餘裕)   夜盤
#      [05:00:05, 08:30)       休市
#
#  「試撮結束」不必給 —— 它等於盤中開始。
#  **收尾餘裕不是獨立狀態**,是盤段的延長 ⇒ 餘裕內仍然「要嘛日盤要嘛夜盤」。
#  這比把收盤與容差熔成一個 `13:45:05` 魔數誠實:
#  **市場事實(收盤 13:45)與工程容差(+5s)分開表達。**
# ══════════════════════════════════════════════════════════════════════════
DAY_PREOPEN_START = time(8, 30)      # 日盤試撮開始
DAY_OPEN = time(8, 45)               # 日盤開始(真實撮合)
DAY_CLOSE = time(13, 45)             # 日盤結束(市場事實,不含容差)
NIGHT_PREOPEN_START = time(14, 50)   # 夜盤試撮開始
NIGHT_OPEN = time(15, 0)             # 夜盤開始
NIGHT_CLOSE = time(5, 0)             # 夜盤結束(跨午夜,落在翌日凌晨)

#: 收尾餘裕(秒),**日夜共用**。
#  全史 1.16 億列 raw tick 實測【實測】:
#      日盤收 13:45:00 之後  449 筆,最大超出 **0.111 秒**
#      夜盤收 05:00:00 之後   75 筆,最大超出 **0.105 秒**
#  ⇒ 5 秒是 45 倍餘裕。整條尾巴共 524 筆 / 1.16 億(4.5e-6)。
CLOSE_GRACE_SEC = 5

# ══════════════════════════════════════════════════════════════════════════
#  §4 第八個值:歸檔日期樞紐
#
#  🔒🔒 **它與 `DAY_PREOPEN_START` 必須是兩個名字,即使現在同值。** 🔒🔒
#
#      `DAY_PREOPEN_START` = **市場事實**(試撮真的在 08:30 開始)
#      `ARCHIVE_DATE_PIVOT` = **死區內的一個切點**,純粹是工程選擇
#
#  它們碰巧同值,不是同一件事。舊碼把兩者壓成一個 `DAY_START` 借來借去
#  ——「試撮時間改了,樞紐不該跟著動」正是必須拆名的理由。
#  ⇒ 這裡刻意寫成**獨立字面值**,不是 `ARCHIVE_DATE_PIVOT = DAY_PREOPEN_START`。
#     寫成後者的話,改試撮時間就會**靜靜地**改掉六年 parquet 的歸檔語意。
#
#  用途:夜盤跨午夜,`00:00–05:00` 若照原日期歸檔會跟前半段分裂成兩天 ⇒
#        `ts.time() < ARCHIVE_DATE_PIVOT` → `date` 退一天,整夜黏回同一個 `date`。
#        (所以湖的 `date` 欄是**盤段錨日**,不是交易日;檔名才是交易日。)
#
#  合法範圍(不變量):
#        夜盤結束 + 餘裕  <  ARCHIVE_DATE_PIVOT  ≤  日盤試撮開始
#        即 05:00:05 < 樞紐 ≤ 08:30 —— 也就是「早上那段休市死區」之內。
#  為什麼死區內可以隨便挪:該區間 `[05:00:05, 08:30)` 在三商品 **1.29 億列**中
#  實測 **0 列**【實測】,所以移動不影響任何既存資料。
#  ⚠️ 但**移出死區**會讓真實資料被重新歸屬 → 舊檔新檔同一個 `date` 欄兩種語意,
#     **而且不會報錯**。
#
#  ⚠️ 它的**值**是 schema 歷史(六年 `date` 欄用它寫的),凍結。
# ══════════════════════════════════════════════════════════════════════════
ARCHIVE_DATE_PIVOT = time(8, 30)


# ══════════════════════════════════════════════════════════════════════════
#  推導值 —— **不是第九、第十個設定**,是上面那些算出來的
#
#  這兩個就是「收盤 + 容差」熔成的那個魔數(`13:45:05`)的來源分解。分開表達之後,
#  「收盤時刻」與「容差」可以各自被討論、被測試、被改,而不是綁在一個看不出成因的字面值裡。
# ══════════════════════════════════════════════════════════════════════════
def _plus_seconds(t: time, secs: float) -> time:
    """`t + secs` 的時刻部分。只在 import 時各跑一次,不在熱路徑上。"""
    return (datetime.combine(date(2000, 1, 1), t) + timedelta(seconds=secs)).time()


DAY_CLOSE_WITH_GRACE = _plus_seconds(DAY_CLOSE, CLOSE_GRACE_SEC)        # 13:45:05
NIGHT_CLOSE_WITH_GRACE = _plus_seconds(NIGHT_CLOSE, CLOSE_GRACE_SEC)    # 05:00:05


# ══════════════════════════════════════════════════════════════════════════
#  §1 五個狀態 —— 完整覆蓋 24 小時,無縫無疊
#
#  🔑 **這一節才是整套設計的價值所在,不是上面那些常數。**
#     常數換名字買到的是 0(新舊值全部相等,實測 86400 秒逐秒行為不變);
#     真正的收穫是**值域裡終於有「休市」** —— 它讓「現在沒有盤」從一個
#     「答不出來所以回最接近的答案」變成一個**可以拿來做事的值**。
#
#  舊系統沒有這個值,所以任何越界的東西都會被靜靜折進最近的桶,而且不吭聲:
#      被問「現在有沒有盤?」      → 回答「Day 還是 Night」  → 14:00 回 Night
#      被問「這 tick 屬於哪根棒?」→ 回答「最接近的合法棒」  → 晚 9.93 小時也折回去
#  ⇒ 設計目標不是「分類正確」,是**讓錯誤的答案發出聲音**。
# ══════════════════════════════════════════════════════════════════════════
class Phase(StrEnum):
    """一天之內的五個盤段狀態。

    用 `StrEnum` 而不是裸字串:打錯名字會是 `AttributeError`(**大聲**),
    而裸字串打錯只會靜靜比不相等 —— 那正是這套設計要消滅的失效模式。
    而它同時**是** `str`,所以 `Phase.DAY == "DAY"` 為真、能直接進 f-string、
    能當 dict 鍵與湖裡的字串比對,呼叫端一個字都不用改。

    ⚠️ `StrEnum` 需要 **Python 3.11+**(工作站統一 3.13)。刻意不用
      `class Phase(str, Enum)`:那個寫法的 `__str__` 行為在 3.11/3.12 之間變過,
      而本檔要逐位元複製到三個 repo —— 跨版本行為不確定的東西不該進來。
    """
    DAY_PREOPEN = "DAY_PREOPEN"      # [08:30, 08:45)          日盤試撮
    DAY = "DAY"                      # [08:45, 13:45 + 餘裕)   日盤(含收尾餘裕)
    CLOSED = "CLOSED"                # [13:45:05, 14:50) 與 [05:00:05, 08:30)
    NIGHT_PREOPEN = "NIGHT_PREOPEN"  # [14:50, 15:00)          夜盤試撮
    NIGHT = "NIGHT"                  # [15:00, 05:00 + 餘裕)   夜盤(跨午夜,含餘裕)


# 模組層別名 —— 呼叫端可以寫 `phase is DAY` 或 `Phase.DAY`,兩種都對(同一個物件)。
DAY_PREOPEN = Phase.DAY_PREOPEN
DAY = Phase.DAY
CLOSED = Phase.CLOSED
NIGHT_PREOPEN = Phase.NIGHT_PREOPEN
NIGHT = Phase.NIGHT

#: 五個狀態的完整清單(順序 = 一天之內的出現順序,不含跨午夜的回繞)
PHASES = (NIGHT, CLOSED, DAY_PREOPEN, DAY, NIGHT_PREOPEN)


def phase_of_day(ts: datetime) -> Phase:
    """本函式假設今天是交易日。回答「一天之內的哪一段」—— 純時鐘、零日曆。

    它**答不出今天有沒有開市**:週日 12:00 一樣回 `DAY`。這不是缺陷,是分工 ——
    本工作區**刻意不維護交易日曆**(ETL 的幻影守衛:「免維護交易日曆」,颱風休市
    免費涵蓋),那個決定不推翻。所以三個問題分給三個答得出來的人:

        phase_of_day(ts)            一天之內的哪一段     純時鐘,不需要日曆
        is_trading_day(d, 資料源)   今天有沒有開市       資料驅動,離線可答
        live 的「現在開著嗎」       **不要算,用觀察的** tick 有在流就是開著

    🔒 因此這個概念的名字裡**不可出現 `is_market_open`** —— 那個名字承諾了
      時鐘給不出的東西,而承諾了又給不出的失效方式是**安靜的**。

    ⚠️ `ts` 的**日期部分被刻意忽略**。那正是「日曆正交」這個性質本身,不是偷懶:
      換成週日、假日、閏日,同一個時刻必須回同一個答案。

    ⚠️ 兩個試撮窗**目前在 tick 流裡都是 0 筆**(producer 濾掉 simtrade)。
      分類照樣把它們算出來,是為了讓「試撮不成棒」這條規則有地方可以寫,
      而不是留一個沒有規格的洞。

    ## 🔑 試撮錨定不對稱:二選一,這裡選了「不進分桶」

    舊碼兩個試撮窗的錨定**方向相反**(實測):

        08:35(日盤試撮) → 1m bucket 08:35     往前錨,當場開一根真棒
        14:55(夜盤試撮) → 1m bucket 04:59     往後錨,**落後 9.93 小時**

    成因:夜側「屬於哪一晚」的規則是 `時刻 < 15:00 → 前一晚`,那是為凌晨
    `00:00–05:00` 寫的,而 `14:50–15:00` 也滿足同一條件。

    **選 B:依「試撮不成棒」讓兩個試撮窗根本不進分桶。**
    (選項 A 是把夜盤試撮改成往前錨、與日側對稱。)

    為什麼選 B:
      1. **A 只是把不對稱換個方向,B 讓問題消失。** 試撮既然不成棒,「錨在哪」
         就是一個**不需要有答案**的問題。留著一個沒人用卻要維護正確性的答案,
         就是下一個「加了標準卻零呼叫端」。
      2. **A 要動夜側的日期規則**,而那條規則同時服務凌晨 `00:00–05:00`
         (真的有資料的區間),改它的風險遠大於它解決的問題(試撮窗全史 0 筆)。
      3. B 的落實處在**各 repo 的分桶層**,不在本檔 —— 本檔只回答「這是哪一段」,
         「要不要成棒」是分桶層的決定。
    """
    t = ts.time()
    if t < NIGHT_CLOSE_WITH_GRACE:      # [00:00, 05:00:05)  前一晚夜盤的下半段
        return NIGHT
    if t < DAY_PREOPEN_START:           # [05:00:05, 08:30)  早上死區
        return CLOSED
    if t < DAY_OPEN:                    # [08:30, 08:45)
        return DAY_PREOPEN
    if t < DAY_CLOSE_WITH_GRACE:        # [08:45, 13:45:05)
        return DAY
    if t < NIGHT_PREOPEN_START:         # [13:45:05, 14:50)  午間死區
        return CLOSED
    if t < NIGHT_OPEN:                  # [14:50, 15:00)
        return NIGHT_PREOPEN
    return NIGHT                        # [15:00, 24:00)


# ══════════════════════════════════════════════════════════════════════════
#  §3 對照表:五狀態 → 歸檔標籤
#
#  湖的 `session` 欄是**分區鍵**,每一列都必須落到某處 ⇒ 值域**必須維持
#  `{Day, Night}`,不可擴充**。所以標籤不是第六、第七個狀態,而是五狀態的一個**投影**:
#
#      日盤試撮 + 日盤 + 日盤餘裕  →  Day
#      夜盤試撮 + 夜盤 + 夜盤餘裕  →  Night
#      休市                        →  Night(**維持舊行為**)
#
#  🔑 這個投影是**有損**的,而那正是「湖零遷移」成立的原因:
#     `DAY_PREOPEN ∪ DAY` 投影後與舊的二值判定完全同界 ⇒ 六年資料一列都不用動。
#  ⚠️ 反過來說:標籤層看不見的東西(08:45、14:50、15:00、05:00 這四個邊界)
#     就**不能**靠它來守。實測同一個錯模型在 phase 層 910 秒不同、標籤層只有 905 秒
#     —— 差的 5 秒就是夜盤餘裕,它兩側都投影成 Night。
#
#  ⚠️ 「休市 → Night」是**刻意維持舊行為**,不是說休市屬於夜盤。
#     休市該怎麼被**處置**(丟棄 + 吵)是分桶層的事,不是歸檔層的事 ——
#     歸檔層只負責「這一列要寫進哪個分區」,而它必須回答得出來。
# ══════════════════════════════════════════════════════════════════════════
ARCHIVE_LABEL = {
    DAY_PREOPEN: "Day",
    DAY: "Day",
    NIGHT_PREOPEN: "Night",
    NIGHT: "Night",
    CLOSED: "Night",
}


def archive_label(ts: datetime) -> str:
    """`ts` 這一列該寫進湖的哪個 `session` 分區。值域恆為 `{Day, Night}`。

    = `ARCHIVE_LABEL[phase_of_day(ts)]`。刻意做成薄包裝而不是各自判斷 ——
    標籤**必須**是 phase 的投影,否則兩者會各自漂(那正是舊碼裡 scalar 版與
    polars 版兩支孿生的處境:值相同純屬運氣,而註解已經漂開了)。
    """
    return ARCHIVE_LABEL[phase_of_day(ts)]
